#!/usr/bin/env node
/* Records the soundboard effects with ElevenLabs sound generation and writes js/sfx-manifest.js.
   js/audio.js plays these clips and falls back to its own synthesised sounds when one is missing.
   Effects whose description and length have not changed are skipped.

   Needs ELEVENLABS_API_KEY in .env.local (git-ignored) with the "Sound Effects" permission.

   node scripts/generate-sfx.js                  record everything that changed
   node scripts/generate-sfx.js --dry-run        show what would be recorded
   node scripts/generate-sfx.js --only bell,toll record just these
   node scripts/generate-sfx.js --force          record again even if unchanged (a new take) */
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const ROOT = path.join(__dirname, '..');
const OUT_DIR = path.join(ROOT, 'assets', 'sfx');
const MANIFEST = path.join(ROOT, 'js', 'sfx-manifest.js');

/* One entry per soundboard name in js/audio.js. seconds: 0.5 to 30. influence: how literally the
   description is followed (0 to 1). volume: playback level in the game, 0 to 1. */
const EFFECTS = {
  bell: { seconds: 4, influence: 0.6, volume: 0.8, text: 'A single strike of a large old church bell in a stone hall, deep and clear, with a long ringing decay. Gothic, atmospheric.' },
  thunder: { seconds: 5, influence: 0.6, volume: 0.9, text: 'A sharp close crack of thunder followed by a long deep rolling rumble across the sky on a stormy night.' },
  heartbeat: { seconds: 4, influence: 0.7, volume: 0.9, text: 'A slow, heavy human heartbeat, four deep low thumps, tense horror atmosphere, no music.' },
  tick: { seconds: 0.5, influence: 0.7, volume: 0.6, text: 'A single crisp tick of an old wooden grandfather clock.' },
  whisper: { seconds: 3, influence: 0.6, volume: 0.8, text: 'Eerie ghostly whispering of a woman, unintelligible and breathy, echoing softly through an empty old house.' },
  scream: { seconds: 2, influence: 0.6, volume: 0.8, text: 'A woman gasps and lets out a short horrified scream in a large old room, then silence.' },
  puff: { seconds: 0.8, influence: 0.7, volume: 0.7, text: 'A candle flame blown out with a short soft puff of breath and a tiny hiss of smoke.' },
  death: { seconds: 4, influence: 0.55, volume: 0.9, text: 'A wine glass shatters on a stone floor, a body collapses heavily, then a deep boom of thunder. Horror film.' },
  ghost: { seconds: 5, influence: 0.5, volume: 0.8, text: 'A ghost appears: a cold rising wind, a distant eerie choir tone and a faint chime, haunting and supernatural.' },
  toll: { seconds: 7, influence: 0.6, volume: 0.8, text: 'A deep mournful funeral bell tolling slowly three times in an old stone church, long echoes between the strikes.' }
};

function readKey() {
  if (process.env.ELEVENLABS_API_KEY) return process.env.ELEVENLABS_API_KEY.trim();
  const file = path.join(ROOT, '.env.local');
  if (fs.existsSync(file)) {
    const m = fs.readFileSync(file, 'utf8').match(/^ELEVENLABS_API_KEY=(.+)$/m);
    if (m) return m[1].trim();
  }
  return null;
}

function readManifest() {
  if (!fs.existsSync(MANIFEST)) return { clips: {} };
  const m = fs.readFileSync(MANIFEST, 'utf8').match(/\/\* DATA \*\/([\s\S]*)\/\* END \*\//);
  return m ? JSON.parse(m[1]) : { clips: {} };
}

function writeManifest(manifest) {
  fs.writeFileSync(MANIFEST, `/* Generated by scripts/generate-sfx.js: recorded soundboard effects, played by js/audio.js. */
(function (root) {
  const manifest = /* DATA */${JSON.stringify(manifest, null, 2)}/* END */;
  root.BM = root.BM || {};
  root.BM.sfx = manifest;
  if (typeof module !== 'undefined' && module.exports) module.exports = manifest;
})(typeof window !== 'undefined' ? window : globalThis);
`);
}

const hashFor = (e) => crypto.createHash('sha1').update(JSON.stringify([e.text, e.seconds, e.influence])).digest('hex').slice(0, 12);
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function record(key, name, e) {
  for (let attempt = 1; attempt <= 4; attempt++) {
    const res = await fetch('https://api.elevenlabs.io/v1/sound-generation', {
      method: 'POST',
      headers: { 'xi-api-key': key, 'Content-Type': 'application/json' },
      body: JSON.stringify({ text: e.text, duration_seconds: e.seconds, prompt_influence: e.influence })
    });
    if (res.ok) return Buffer.from(await res.arrayBuffer());
    const body = await res.text();
    if ((res.status === 429 || res.status >= 500) && attempt < 4) { await sleep(2000 * attempt); continue; }
    throw new Error(`ElevenLabs ${res.status} on effect "${name}": ${body.slice(0, 300)}`);
  }
  throw new Error(`ElevenLabs kept failing on effect "${name}"`);
}

async function main() {
  const args = process.argv.slice(2);
  const dry = args.includes('--dry-run');
  const force = args.includes('--force');
  const onlyArg = args[args.indexOf('--only') + 1];
  const only = args.includes('--only') && onlyArg ? new Set(onlyArg.split(',')) : null;

  const manifest = readManifest();
  const todo = Object.entries(EFFECTS).filter(([name, e]) => {
    if (only && !only.has(name)) return false;
    const have = manifest.clips[name];
    return force || !have || have.hash !== hashFor(e) || !fs.existsSync(path.join(ROOT, have.src));
  });
  console.log(`${todo.length} of ${Object.keys(EFFECTS).length} effects to record.`);
  todo.forEach(([name, e]) => console.log(`  ${name.padEnd(10)} ${String(e.seconds).padStart(4)}s  ${e.text}`));
  if (dry || !todo.length) return;

  const key = readKey();
  if (!key) { console.error('No ELEVENLABS_API_KEY in the environment or in .env.local.'); process.exit(1); }
  fs.mkdirSync(OUT_DIR, { recursive: true });
  for (const [name, e] of todo) {
    const audio = await record(key, name, e);
    fs.writeFileSync(path.join(OUT_DIR, `${name}.mp3`), audio);
    manifest.clips[name] = { src: `assets/sfx/${name}.mp3`, hash: hashFor(e), seconds: e.seconds, volume: e.volume };
    writeManifest(manifest);
    console.log(`  recorded ${name} (${audio.length} bytes)`);
  }
  console.log('Done. Commit assets/sfx and js/sfx-manifest.js to publish.');
}

main().catch((e) => { console.error(e.message); process.exit(1); });
